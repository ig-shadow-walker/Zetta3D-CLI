/**
 * Writes docs/COMMANDS.md from the command definitions, so the reference never drifts from the code,
 * and builds the agent skill from it and docs/: the references the binary embeds
 * (packages/cli/src/skill/docs.generated.ts) and the browsable copy in skill/zetta3d/.
 * Run with `bun run docs:commands`.
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { COMMANDS, GROUPS } from '../packages/cli/src/commands'
import { SKILL_NAME, skillMarkdown } from '../packages/cli/src/guide'
import { commandReference } from '../packages/cli/src/skill/reference'
import { buildReferenceDocs } from '../packages/cli/src/skill/sources'

const root = join(import.meta.dir, '..')
const commands = commandReference(COMMANDS, GROUPS)
writeFileSync(join(root, 'docs', 'COMMANDS.md'), commands)

// The skill's reference files, embedded in the binary (it has no docs folder of its own).
const references = buildReferenceDocs((doc) => readFileSync(join(root, 'docs', doc), 'utf8'))
writeFileSync(
  join(root, 'packages', 'cli', 'src', 'skill', 'docs.generated.ts'),
  [
    '// Generated by `bun run docs:commands` from docs/ (see skill/sources.ts). Do not edit by hand.',
    '',
    'export const SKILL_DOCS: Record<string, string> = {',
    ...Object.entries(references).map(([file, text]) => `  ${JSON.stringify(file)}: ${JSON.stringify(text)},`),
    '}',
    '',
  ].join('\n'),
)

// The same skill as a folder in the repository, for people and for skill installers that read repos.
const skillDir = join(root, 'skill', SKILL_NAME)
rmSync(skillDir, { recursive: true, force: true })
rmSync(join(root, 'skill', 'SKILL.md'), { force: true })
const files = { 'SKILL.md': skillMarkdown(), ...Object.fromEntries(Object.entries(references).map(([f, t]) => [`references/${f}`, t])), 'references/commands.md': commands }
for (const [rel, text] of Object.entries(files)) {
  mkdirSync(dirname(join(skillDir, rel)), { recursive: true })
  writeFileSync(join(skillDir, rel), text)
}
console.log(`Wrote docs/COMMANDS.md (${COMMANDS.length} commands), the embedded skill references and skill/${SKILL_NAME}/ (${Object.keys(files).length} files).`)
