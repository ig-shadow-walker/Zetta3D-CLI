/**
 * Builds the extra install channels from a finished `bun run build` (dist/latest.json + binaries):
 *
 *   dist/homebrew/zetta.rb   a Homebrew formula pointing at the download host
 *   dist/npm/<package>/      npm packages: `@zetta3d/cli` (a tiny launcher) plus one package per
 *                            platform carrying the binary, picked by npm through os/cpu/libc
 *
 *   bun run package:channels [--download-base <url>]   (default: the GitHub releases)
 *
 * Nothing is published. The release workflow (or the owner) publishes the npm packages with
 * `npm publish --access public` in each folder, platform packages first, and commits the formula
 * to the Homebrew tap repository.
 */
import { chmodSync, copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { parseArgs } from 'node:util'
import { downloadBase, parseManifest, versionUrl, type LatestManifest } from '../packages/cli/src/upgrade/manifest'

const { values } = parseArgs({ options: { 'download-base': { type: 'string' }, dist: { type: 'string' } } })
const ROOT = join(import.meta.dir, '..')
const DIST = values.dist ?? join(ROOT, 'dist')
const BASE = downloadBase(values['download-base'])

const latestPath = join(DIST, 'latest.json')
if (!existsSync(latestPath)) {
  console.error('dist/latest.json not found. Run `bun run build` first.')
  process.exit(1)
}
const manifest: LatestManifest = parseManifest(JSON.parse(readFileSync(latestPath, 'utf8')), latestPath)
const version = manifest.version
const url = (name: string) => versionUrl(BASE, version, name)

// ── Homebrew ────────────────────────────────────────────────────────────────

const brewTargets: Array<[os: 'macos' | 'linux', cpu: 'arm' | 'intel', key: string]> = [
  ['macos', 'arm', 'darwin-arm64'],
  ['macos', 'intel', 'darwin-x64'],
  ['linux', 'arm', 'linux-arm64'],
  ['linux', 'intel', 'linux-x64'],
]
const blocks: Record<'macos' | 'linux', string[]> = { macos: [], linux: [] }
for (const [os, cpu, key] of brewTargets) {
  const file = manifest.files[key]
  if (!file) continue
  blocks[os].push(`    on_${cpu} do\n      url "${url(file.name)}"\n      sha256 "${file.sha256}"\n    end`)
}
if (!blocks.macos.length && !blocks.linux.length) {
  console.error('No macOS or Linux binaries in dist/latest.json; build them first (bun run build).')
  process.exit(1)
}
const formula = `# Generated by scripts/package-channels.ts from dist/latest.json. Do not edit by hand.
class Zetta < Formula
  desc "Zetta 3D from the terminal: 3D models from text or pictures, for people and AI agents"
  homepage "https://zetta3d.ai"
  version "${version}"
${blocks.macos.length ? `\n  on_macos do\n${blocks.macos.join('\n')}\n  end\n` : ''}${blocks.linux.length ? `\n  on_linux do\n${blocks.linux.join('\n')}\n  end\n` : ''}
  def install
    binary = Dir["zetta-*"].first || "zetta"
    bin.install binary => "zetta"
  end

  # Teaches the AI coding agents found here (Claude Code, Codex, Cursor) to use zetta.
  # Skipped with ZETTA_NO_SKILL=1 or after "zetta skill uninstall"; never fails the install.
  def post_install
    system bin/"zetta", "skill", "install", "--auto", "--output", "text"
  rescue StandardError
    nil
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/zetta --version")
  end
end
`
mkdirSync(join(DIST, 'homebrew'), { recursive: true })
writeFileSync(join(DIST, 'homebrew', 'zetta.rb'), formula)

// ── npm ─────────────────────────────────────────────────────────────────────

const NPM_PLATFORMS: Record<string, { os: string; cpu: string; libc?: string; exe?: boolean }> = {
  'darwin-arm64': { os: 'darwin', cpu: 'arm64' },
  'darwin-x64': { os: 'darwin', cpu: 'x64' },
  'linux-x64': { os: 'linux', cpu: 'x64', libc: 'glibc' },
  'linux-arm64': { os: 'linux', cpu: 'arm64', libc: 'glibc' },
  'linux-x64-musl': { os: 'linux', cpu: 'x64', libc: 'musl' },
  'linux-arm64-musl': { os: 'linux', cpu: 'arm64', libc: 'musl' },
  'windows-x64': { os: 'win32', cpu: 'x64', exe: true },
}
const npmRoot = join(DIST, 'npm')
rmSync(npmRoot, { recursive: true, force: true })
const optional: Record<string, string> = {}
const packaged: string[] = []

for (const [key, platform] of Object.entries(NPM_PLATFORMS)) {
  const file = manifest.files[key]
  const source = file ? join(DIST, `v${version}`, file.name) : undefined
  if (!file || !source || !existsSync(source)) continue
  const name = `@zetta3d/cli-${key}`
  const dir = join(npmRoot, `cli-${key}`)
  mkdirSync(join(dir, 'bin'), { recursive: true })
  const binary = join(dir, 'bin', platform.exe ? 'zetta.exe' : 'zetta')
  copyFileSync(source, binary)
  chmodSync(binary, 0o755)
  writeFileSync(
    join(dir, 'package.json'),
    `${JSON.stringify(
      {
        name,
        version,
        description: `The zetta binary for ${key}. Install @zetta3d/cli instead.`,
        homepage: 'https://zetta3d.ai',
        os: [platform.os],
        cpu: [platform.cpu],
        ...(platform.libc ? { libc: [platform.libc] } : {}),
        files: ['bin'],
        preferUnplugged: true,
      },
      null,
      2,
    )}\n`,
  )
  optional[name] = version
  packaged.push(name)
}

const main = join(npmRoot, 'cli')
mkdirSync(join(main, 'bin'), { recursive: true })
writeFileSync(
  join(main, 'package.json'),
  `${JSON.stringify(
    {
      name: '@zetta3d/cli',
      version,
      description: 'Zetta 3D from the terminal: 3D models from text or pictures, for people and AI agents.',
      homepage: 'https://zetta3d.ai',
      bin: { zetta: 'bin/zetta.js' },
      scripts: { postinstall: 'node bin/postinstall.js' },
      files: ['bin', 'README.md'],
      engines: { node: '>=18' },
      optionalDependencies: optional,
    },
    null,
    2,
  )}\n`,
)
writeFileSync(
  join(main, 'bin', 'zetta.js'),
  `#!/usr/bin/env node
// Runs the zetta binary for this platform, installed by npm as an optional dependency.
'use strict'
const { spawnSync } = require('node:child_process')
const { readFileSync } = require('node:fs')

function isMusl() {
  if (process.platform !== 'linux') return false
  try {
    return readFileSync('/usr/bin/ldd', 'utf8').includes('musl')
  } catch {
    const report = process.report && process.report.getReport && process.report.getReport()
    return Boolean(report && report.header && !report.header.glibcVersionRuntime)
  }
}

const os = process.platform === 'win32' ? 'windows' : process.platform
const key = \`\${os}-\${process.arch}\${isMusl() ? '-musl' : ''}\`
let binary
try {
  binary = require.resolve(\`@zetta3d/cli-\${key}/bin/zetta\${os === 'windows' ? '.exe' : ''}\`)
} catch {
  console.error(\`zetta: no binary for \${key}. Reinstall @zetta3d/cli, or use the installer: curl -fsSL https://zetta3d.ai/install.sh | sh\`)
  process.exit(1)
}
const result = spawnSync(binary, process.argv.slice(2), { stdio: 'inherit' })
if (result.error) {
  console.error(\`zetta: could not start \${binary}: \${result.error.message}\`)
  process.exit(1)
}
if (result.signal) process.kill(process.pid, result.signal)
process.exit(result.status ?? 1)
`,
)
chmodSync(join(main, 'bin', 'zetta.js'), 0o755)
writeFileSync(
  join(main, 'bin', 'postinstall.js'),
  `// Teaches the AI coding agents found here (Claude Code, Codex, Cursor) to use zetta: installs the
// Zetta 3D skill for them. Skipped with ZETTA_NO_SKILL=1 or after \`zetta skill uninstall\`.
// Never fails the npm install.
'use strict'
if (process.env.ZETTA_NO_SKILL === '1' || process.env.CI === 'true') process.exit(0)
try {
  require('node:child_process').spawnSync(process.execPath, [require('node:path').join(__dirname, 'zetta.js'), 'skill', 'install', '--auto'], { stdio: 'ignore', timeout: 30000 })
} catch {}
`,
)
writeFileSync(
  join(main, 'README.md'),
  `# @zetta3d/cli\n\nZetta 3D from the terminal. \`npx @zetta3d/cli --help\`, or \`npm i -g @zetta3d/cli\` then \`zetta --help\`.\n\nThe recommended install needs no Node at all: \`curl -fsSL https://zetta3d.ai/install.sh | sh\`. See https://zetta3d.ai for documentation.\n`,
)

console.log(`Homebrew: dist/homebrew/zetta.rb (${blocks.macos.length + blocks.linux.length} platforms)`)
console.log(`npm: dist/npm/cli (@zetta3d/cli ${version}) + ${packaged.length} platform package(s): ${packaged.join(', ')}`)
